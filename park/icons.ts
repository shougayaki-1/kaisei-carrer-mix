/** Replace any <i data-lucide="..."> with a matching inline SVG. */
export function renderIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-lucide]').forEach((placeholder) => {
    const name = placeholder.dataset.lucide;
    const shape = name ? shapes[name] : undefined;
    if (!shape) return;
    const svg = document.createElementNS('http://www.w3.org/2000/svg','svg');
    svg.setAttribute('xmlns','http://www.w3.org/2000/svg');
    svg.setAttribute('width','24');
    svg.setAttribute('height','24');
    svg.setAttribute('viewBox','0 0 24 24');
    svg.setAttribute('fill','none');
    svg.setAttribute('stroke','currentColor');
    svg.setAttribute('stroke-width','2');
    svg.setAttribute('stroke-linecap','round');
    svg.setAttribute('stroke-linejoin','round');
    svg.setAttribute('aria-hidden',placeholder.getAttribute('aria-hidden') || 'true');
    if (placeholder.className) svg.setAttribute('class',placeholder.className);
    // The markup is a static, trusted Lucide asset bundled in this module.
    svg.innerHTML = shape;
    placeholder.replaceWith(svg);
  });
}
